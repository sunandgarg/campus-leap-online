const palette = [
  "oklch(0.5 0.14 250)",
  "oklch(0.52 0.15 35)",
  "oklch(0.48 0.13 155)",
  "oklch(0.5 0.13 305)",
  "oklch(0.5 0.12 205)",
  "oklch(0.54 0.14 80)",
];

function createDirectoryUniversity(
  university: DirectoryUniversityInput,
  index: number,
): University {
  return {
    ...university,
    established: university.established ?? 0,
    domain: "",
    accentColor: palette[index % palette.length] ?? "oklch(0.5 0.14 250)",
    naacGrade: "Verify",
    approvals: ["UGC-DEB source-listed", "Intake verification required"],
    rating: 0,
    reviews: 0,
    studentsEnrolled: "Not publicly stated",
    placementPartners: [],
    highlights: [
      "Included in the UGC-DEB 2025–26 entitled HEI notice",
      "Course availability must be checked for the learner's exact intake",
      "Fees, examinations and support details are awaiting editorial verification",
    ],
    about: `${university.name} appears in the UGC-DEB 2025–26 notice for entitled higher-education institutions offering online programmes. DekhoCampus currently maintains this as a directory-stage profile. Confirm the exact programme, academic session, fee and admission route on the current UGC-DEB and university websites before applying or paying.`,
    programs: university.programs.map((slug) => ({
      slug,
      feesVerified: false,
      specialisationsVerified: false,
    })),
    profileDepth: "directory",
    verificationAcademicYear: "2025–26",
    verificationSourceUrl: UGC_DEB_SOURCE,
    lastVerified: "12 September 2026",
    metricsVerified: false,
  };
}

